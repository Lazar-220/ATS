// Generates src/api-types.ts from openapi.json (written by `python -m ats.api.openapi`).
// With --check it writes nothing and exits 1 when the committed file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const schema = new URL("../openapi.json", import.meta.url);
const target = fileURLToPath(new URL("../src/api-types.ts", import.meta.url));

const banner = "// Generated by scripts/gen-types.mjs from openapi.json. Do not edit; run `make api-types`.\n\n";
const generated = banner + astToString(await openapiTS(schema)).replace(/\r\n/g, "\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // a missing file counts as stale
  }
  if (current !== generated) {
    console.error("web/src/api-types.ts is stale against web/openapi.json: run `make api-types`.");
    process.exit(1);
  }
} else {
  writeFileSync(target, generated);
}
